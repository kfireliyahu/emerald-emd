-- 019_deposit_origins — two more ways a balance can have arrived: it was already
-- there, or it grew. See docs/f07-savings-and-deposits.md and D-081.
--
-- Numbered and immutable after release (D-020).
--
-- **The whole migration is one CHECK constraint**, and it costs a table rebuild
-- because SQLite cannot alter one. `saving_deposit.source_kind` has permitted
-- four values since 018; it now permits six, adding `OPENING_BALANCE` and
-- `GROWTH`.
--
-- **Why they are source kinds rather than notes on a MANUAL row.** docs/f07's
-- open question recommended recording an investment gain as an ordinary manual
-- deposit with an explanatory note, and that recommendation is superseded here.
-- A balance is Σ its deposits and must stay so — the money is genuinely in the
-- goal, so it belongs in the sum — but *how it got there* is a different fact
-- from *how much*, and exactly one figure downstream depends on it: docs/05's
-- effective savings rate is money the user put aside, and neither an opening
-- balance nor a market gain is that. A note cannot be read by an aggregate. A
-- source kind can, and the same term already carries `FROM_PAYCHECK_DEDUCTION`
-- for the same reason (D-077).
--
-- **`GROWTH` may be negative and `OPENING_BALANCE` should not be.** A loss is a
-- real event that must be recordable, or a user whose portfolio fell has no way
-- to make the app agree with their statement except by inventing a withdrawal —
-- which would be counted as money spent. The domain requires a reason on a
-- negative deposit precisely so a balance never drops unexplained; that
-- requirement is lifted for `GROWTH` alone, because "the market fell" is what
-- the kind already says.
--
-- The rebuild is the standard four steps, and everything else about the table is
-- carried across unchanged — same columns, same order, same defaults, same
-- indexes, same partial-unique predicate. Nothing in `saving_deposit` is
-- referenced by another table's foreign key, and this app never sets
-- `PRAGMA foreign_keys = ON` (D-067), so the rename cannot orphan anything.

CREATE TABLE saving_deposit_new (
  id                TEXT PRIMARY KEY NOT NULL,
  goal_id           TEXT NOT NULL REFERENCES saving_goal (id),
  date              TEXT NOT NULL,
  currency          TEXT NOT NULL,
  -- **Negative for a withdrawal**, and now also for a loss. Never zero.
  amount_minor      INTEGER NOT NULL,
  holding_place_id  TEXT NOT NULL REFERENCES holding_place (id),
  -- The two new values are the point of this migration. Both are entered by
  -- hand, so neither carries a `source_ref_id` and neither is generated by
  -- anything the app re-derives.
  source_kind       TEXT NOT NULL DEFAULT 'MANUAL' CHECK (source_kind IN (
                      'MANUAL', 'FROM_TRANSACTION', 'FROM_PAYCHECK_DEDUCTION',
                      'FROM_PLAN', 'OPENING_BALANCE', 'GROWTH')),
  source_ref_id     TEXT,
  transfer_group_key TEXT,
  note              TEXT,
  created_at        INTEGER NOT NULL DEFAULT 0,
  updated_at        INTEGER NOT NULL DEFAULT 0,
  deleted_at        INTEGER
);

INSERT INTO saving_deposit_new (
  id, goal_id, date, currency, amount_minor, holding_place_id, source_kind,
  source_ref_id, transfer_group_key, note, created_at, updated_at, deleted_at
)
SELECT
  id, goal_id, date, currency, amount_minor, holding_place_id, source_kind,
  source_ref_id, transfer_group_key, note, created_at, updated_at, deleted_at
FROM saving_deposit;

DROP TABLE saving_deposit;

ALTER TABLE saving_deposit_new RENAME TO saving_deposit;

CREATE INDEX saving_deposit_goal_date ON saving_deposit (goal_id, date);
CREATE INDEX saving_deposit_place ON saving_deposit (holding_place_id);

-- Recreated exactly as 018 wrote it. The predicate excludes `MANUAL` by name and
-- everything with no `source_ref_id` by shape — the two new kinds never carry
-- one, so they need no clause of their own and gaining one would be a second
-- statement of the same rule.
CREATE UNIQUE INDEX saving_deposit_source
  ON saving_deposit (source_kind, source_ref_id)
  WHERE deleted_at IS NULL AND source_kind <> 'MANUAL' AND source_ref_id IS NOT NULL;
